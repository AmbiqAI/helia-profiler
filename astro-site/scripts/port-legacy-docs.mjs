const BASE = '/helia-profiler/';

/*
 * Where a converted page lands, as a prefix rewrite over its docs-relative
 * path. helia-ui matches a section by one path prefix, so User guide content
 * has to sit under guide/; the compatibility baseline is a Reference table
 * that happens to have been filed under architecture/.
 */
const MOVES = [
  ['architecture/compatibility-baseline', 'reference/compatibility-baseline'],
  ['architecture', 'guide/concepts'],
  ['guides', 'guide/in-depth'],
];

const { values } = parseArgs({
  options: {
    out: { type: 'string' },
    report: { type: 'boolean', default: false },
  },
});

const OUT = values.out ? path.resolve(values.out) : CANONICAL;

/** `a/b.md` is read at `a/b/`; `a/index.md` at `a/`. */
const routeDirFor = (relPath) => {
  const parts = relPath.replace(/\.(md|mdx)$/, '').split('/');
  if (parts.at(-1) === 'index') parts.pop();
  return parts.join('/');
};

/** The docs-relative path a converted page is moved to, extension kept. */
const moveOf = (relPath) => {
  const ext = relPath.match(/\.(md|mdx)$/)?.[0] ?? '';
  const stem = relPath.slice(0, relPath.length - ext.length);
  for (const [from, to] of MOVES) {
    if (stem === from || stem.startsWith(`${from}/`))
      return `${to}${stem.slice(from.length)}${ext}`;
  }
  return relPath;
};

const walk = (dir, prefix = '') =>
  fs.existsSync(dir)
    ? fs.readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
        const rel = prefix ? `${prefix}/${entry.name}` : entry.name;
        return entry.isDirectory()
          ? walk(path.join(dir, entry.name), rel)
          : [rel];
      })
    : [];

const mdPages = walk(DOCS)
  .filter((f) => f.endsWith('.md'))
  .sort();
const ported = mdPages.filter((f) => !SKIP.includes(f));

/*
 * Every legacy route, old to new, including the skipped ones: a converted page
 * links to those too, and the link has to survive this port even though the
 * page behind it arrives later.
 */
const routeMap = new Map(
  mdPages.map((f) => [routeDirFor(f), routeDirFor(moveOf(f))]),
);

/**
 * Re-express one link target against the route its page is read from after the
 * move. The converter wrote it against the legacy route, so the target is
 * resolved there first, mapped, then made relative again.
 */
function rewriteTarget(target, fromRoute, toRoute) {
  const [rawPath, hash] = target.split('#');
  const oldRoute = posix.normalize(posix.join(fromRoute, rawPath));
  const isRoute = rawPath.endsWith('/');
  const mapped = isRoute
    ? (routeMap.get(oldRoute === '.' ? '' : oldRoute) ?? oldRoute)
    : oldRoute;
  let rel = posix.relative(toRoute, mapped === '' ? '.' : mapped);
  if (rel === '') rel = './';
  else if (isRoute && !rel.endsWith('/')) rel += '/';
  else if (!rel.startsWith('.')) rel = `./${rel}`;
  return hash === undefined ? rel : `${rel}#${hash}`;
}

/*
 * An anchor into a route that is still a redirect stub names a heading nothing
 * has written yet, and a redirect drops the fragment anyway, so it is removed
 * rather than left to rot.
 * TODO(#331): restore the fragment on links into the CLI, configuration and
 * issue-code pages once those pages exist.
 */
const unbuilt = new Set(
  SKIP.filter((f) => !f.startsWith('reference/api/') && f !== 'index.md').map(
    (f) => routeDirFor(f),
  ),
);

function rewriteLinks(text, fromRoute, toRoute, stats) {
  return text.replace(
    /(!?)\[([^\]]*)\]\(([^)\s]+)(\s+"[^"]*")?\)/g,
    (match, bang, label, target, title) => {
      if (/^(https?:|mailto:|#|\/)/.test(target)) return match;
      let next = rewriteTarget(target, fromRoute, toRoute);
      const [nextPath, hash] = next.split('#');
      if (hash !== undefined) {
        const route = posix.normalize(posix.join(toRoute, nextPath));
        if (unbuilt.has(route === '.' ? '' : route)) {
          next = nextPath;
          stats.anchorsDropped += 1;
        }
      }
      if (next !== target) stats.linksRewritten += 1;
      return `${bang}[${label}](${next}${title ?? ''})`;
    },
  );
}

/*
 * Material's card grid is a `<div class="grid cards">` around a list, painted
 * by a stylesheet this site does not ship, so the converter's verbatim copy
 * renders as a bare list with the octicon shortcode showing as text. The shape
 * is regular enough to read: one list item per card, an icon and a bold title,
 * a rule, the description, and a link. Anything that does not match that shape
 * is left alone and reported, so the rewrite cannot quietly drop a card.
 */
const CARD_OPEN = /^<div class="grid cards">\s*$/;
const CARD_ITEM = /^-\s+(.*)$/;
const CARD_TITLE =
  /^(?:<Icon name="([^"]+)" \/>\s*)?__(.+)__\s*$/;
const CARD_LINK = /^\[(?::[a-z0-9-]+:\s*)?([^\]]*)\]\(([^)\s]+)\)\s*$/;

function parseCard(header, body) {
  const title = header.match(CARD_TITLE);
  if (!title) return null;
  const lines = body
    .map((l) => l.trim())
    .filter((l) => l !== '' && l !== '---');
  const link = lines.length ? lines.at(-1).match(CARD_LINK) : null;
  if (!link) return null;
  const description = lines.slice(0, -1).join(' ').trim();
  if (!description) return null;
  return {
    icon: title[1] ?? null,
    title: title[2].replaceAll('`', '').trim(),
    href: link[2],
    description,
  };
}

function rewriteCardGrids(lines, report) {
  const out = [];
  let used = false;
  for (let i = 0; i < lines.length; i += 1) {
    if (!CARD_OPEN.test(lines[i])) {
      out.push(lines[i]);
      continue;
    }
    let end = i + 1;
    while (end < lines.length && !/^<\/div>\s*$/.test(lines[end])) end += 1;
    const block = lines.slice(i + 1, end);
    const cards = [];
    let ok = end < lines.length;
    let current = null;
    for (const line of block) {
      const item = line.match(CARD_ITEM);
      if (item) {
        if (current) cards.push(current);
        current = { header: item[1], body: [] };
      } else if (current) current.body.push(line);
      else if (line.trim() !== '') ok = false;
    }
    if (current) cards.push(current);
    const parsed = cards.map((c) => parseCard(c.header, c.body));
    if (!ok || parsed.length === 0 || parsed.some((c) => c === null)) {
      report.push('card grid did not match the expected shape; kept verbatim');
      out.push(...lines.slice(i, end + 1));
      i = end;
      continue;
    }
    used = true;
    out.push('<CardGrid>');
    for (const card of parsed) {
      out.push(
        `  <LinkCard href=${JSON.stringify(card.href)} title=${JSON.stringify(card.title)}>`,
      );
      if (card.icon) out.push(`    <Icon name=${JSON.stringify(card.icon)} slot="icon" />`);
      out.push('');
      out.push(`    ${card.description}`);
      out.push('');
      out.push('  </LinkCard>');
    }
    out.push('</CardGrid>');
    i = end;
  }
  return [out, used];
}

/** Put an import beside the ones the converter already wrote. */
function addImports(lines, imports) {
  let at = lines.indexOf('---', lines.indexOf('---') + 1) + 1;
  while (at < lines.length && (lines[at] === '' || lines[at].startsWith('import ')))
    at += 1;
  const head = lines.slice(0, at);
  while (head.at(-1) === '') head.pop();
  if (head.at(-1) === '---') head.push('');
  return [...head, ...imports, '', ...lines.slice(at)];
}

/*
 * The converter's admonition title grammar is a quoted string with no escape,
 * so the one legacy title that quotes a warning message inside double quotes
 * does not parse and the block lands on the page as text. The same title in
 * single quotes is the same characters and does parse. docs/ still publishes
 * the MkDocs site, so this is applied to a staged copy rather than in place.
 */
const VOID_TAGS = new Set(['br', 'hr', 'img', 'input', 'wbr']);

/** Apply `fn` to the parts of a line that are not a code span. */
const outsideCode = (line, fn) =>
  line
    .split(/(`+[^`]*`+)/)
    .map((part, i) => (i % 2 === 1 ? part : fn(part)))
    .join('');

function normaliseSource(text) {
  return text
    .replace(
      /^([ \t]*)(!{3}|\?{3}\+?)([ \t]+[a-z][a-z-]*[ \t]+)(["'])((?:(?!\4).|\\.)*)\4[ \t]*$/gm,
      (match, indent, marker, type, quote, title) => {
        const unescaped = title.replaceAll(`\\${quote}`, quote);
        /* `<` opens a tag in the `:::type[title]` label the converter writes. */
        const safe = unescaped.replaceAll('<', '&lt;');
        if (safe === title) return match;
        if (safe.includes('"') && safe.includes("'")) return match;
        const wrap = safe.includes('"') ? "'" : '"';
        return `${indent}${marker}${type}${wrap}${safe}${wrap}`;
      },
    )
    /*
     * A table row is one line, so a tag opened in a cell and never closed is
     * prose that MkDocs swallowed as markup and that MDX refuses outright.
     */
    .replace(/^[ \t]*\|.*$/gm, (row) =>
      outsideCode(row, (part) =>
        part.replace(/<([a-zA-Z][\w-]*)((?:[^<>"']|"[^"]*"|'[^']*')*)>/g, (tag, name, attrs) =>
          VOID_TAGS.has(name.toLowerCase()) ||
          attrs.trimEnd().endsWith('/') ||
          row.includes(`</${name}>`)
            ? tag
            : `&lt;${name}${attrs}&gt;`,
        ),
      ),
    );
}

const copy = (from, to) => {
  if (!fs.existsSync(from)) return;
  fs.mkdirSync(path.dirname(to), { recursive: true });
  fs.cpSync(from, to, { recursive: true });
};

/* Seed a scratch --out with the authored pages the port carries but does not
 * write, so the tree it produces is comparable with the committed one. */
if (OUT !== CANONICAL) {
  for (const entry of PRESERVE) copy(path.join(CANONICAL, entry), path.join(OUT, entry));
}

const preserved = new Map(
  PRESERVE.filter((entry) => entry.endsWith('.mdx')).map((entry) => [
    entry,
    fs.readFileSync(path.join(OUT, entry), 'utf8'),
  ]),
);

/* Stale pages from an earlier run under the kept reference/ tree. */
for (const entry of fs.readdirSync(path.join(OUT, 'reference'), { withFileTypes: true })) {
  if (entry.isFile() && entry.name.endsWith('.mdx'))
    fs.rmSync(path.join(OUT, 'reference', entry.name));
}

const staged = fs.mkdtempSync(path.join(os.tmpdir(), 'hpx-legacy-docs-'));
for (const rel of walk(DOCS)) {
  const to = path.join(staged, rel);
  fs.mkdirSync(path.dirname(to), { recursive: true });
  if (rel.endsWith('.md'))
    fs.writeFileSync(to, normaliseSource(fs.readFileSync(path.join(DOCS, rel), 'utf8')));
  else fs.copyFileSync(path.join(DOCS, rel), to);
}

const args = [
  '--docs', staged,
  '--config', CONFIG,
  '--out', OUT,
  '--base', BASE,
  '--icons', path.join(here, 'mkdocs-icons.json'),
];
for (const page of SKIP) args.push('--skip', page);
for (const name of KEEP) args.push('--keep', name);
if (values.report) args.push('--report');

const bin = path.join(site, 'node_modules/.bin/helia-ui-mkdocs-convert');
console.log(execFileSync(bin, args, { encoding: 'utf8' }).trimEnd());
fs.rmSync(staged, { recursive: true, force: true });

for (const entry of preserved) {
  const dest = path.join(OUT, entry[0]);
  fs.mkdirSync(path.dirname(dest), { recursive: true });
  fs.writeFileSync(dest, entry[1]);
}

const stats = {
  moved: 0,
  linksRewritten: 0,
  anchorsDropped: 0,
  cardGrids: 0,
  descriptions: 0,
};
const unhandled = [];

for (const page of ported) {
  const fromRel = page.replace(/\.md$/, '.mdx');
  const toRel = moveOf(fromRel);
  const fromPath = path.join(OUT, fromRel);
  const toPath = path.join(OUT, toRel);
  if (fromRel !== toRel) {
    fs.mkdirSync(path.dirname(toPath), { recursive: true });
    fs.renameSync(fromPath, toPath);
    stats.moved += 1;
  }
  const text = fs.readFileSync(toPath, 'utf8');
  let next = rewriteLinks(text, routeDirFor(page), routeDirFor(toRel), stats);

  const report = [];
  let [lines, usedCards] = rewriteCardGrids(next.split('\n'), report);
  if (usedCards) {
    stats.cardGrids += 1;
    lines = addImports(lines, [
      "import CardGrid from '@ambiqai/helia-ui/astro/CardGrid';",
      "import LinkCard from '@ambiqai/helia-ui/astro/LinkCard';",
    ]);
    next = lines.join('\n');
  }
  for (const item of report) unhandled.push(`${page}: ${item}`);

  if (next !== text) fs.writeFileSync(toPath, next);
  if (/^description: "(?!")/m.test(next)) stats.descriptions += 1;
}

/* Directories the moves emptied. */
for (const [from] of MOVES) {
  const dir = path.join(OUT, from);
  if (fs.existsSync(dir) && walk(dir).length === 0) fs.rmSync(dir, { recursive: true });
}

console.log(
  `port-legacy-docs: ${mdPages.length} nav leaves, ${SKIP.length} skipped, ` +
    `${ported.length} ported (${stats.moved} moved, ${stats.linksRewritten} links ` +
    `rewritten, ${stats.anchorsDropped} anchors dropped, ${stats.cardGrids} card ` +
    `grid(s) rebuilt, ${stats.descriptions} with a description).`,
);
/*
 * A page the rewrites could not read is a page that ships broken, and the only
 * run that would show it is this one: check-legacy-port.mjs pipes this output
 * and compares bytes, so a bare list with literal shortcodes in it reproduces
 * happily. Both of these are therefore failures, not warnings.
 */
const failures = unhandled.slice();
if (stats.descriptions !== ported.length) {
  failures.push(
    `${ported.length - stats.descriptions} ported page(s) carry no description`,
  );
}

if (failures.length > 0) {
  console.error('port-legacy-docs: conversion needs a look:\n');
  for (const failure of failures) console.error(`- ${failure}`);
  process.exit(1);
}
