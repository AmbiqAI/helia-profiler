/*
 * The MkDocs tree at docs/ becomes the Astro content collection, mechanically.
 *
 *   node scripts/port-legacy-docs.mjs [--out <dir>] [--report]
 *
 * The conversion itself is helia-ui-mkdocs-convert. What this script adds is
 * the part that is specific to this repository: the skip list, the path moves
 * the five-section information architecture needs, and the link rewrite those
 * moves force. Everything is a pure function of docs/ and mkdocs.yml, so a run
 * into a scratch directory reproduces the committed tree byte for byte, which
 * is what scripts/check-legacy-port.mjs asserts.
 *
 * docs/ stays the published site until cutover (#322), so this runs again
 * whenever a legacy page changes.
 */
